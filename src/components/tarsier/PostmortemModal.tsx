import React, { useState } from 'react';
import {
  X,
  FileText,
  Download,
  Copy,
  Check,
  Calendar,
  Clock,
  Shield,
  AlertTriangle,
  CheckCircle2,
} from 'lucide-react';
import { PostmortemReport } from '../../types/tarsier';
import { SAMPLE_POSTMORTEM } from '../../data/tarsierMockData';

interface PostmortemModalProps {
  isOpen: boolean;
  onClose: () => void;
  report?: PostmortemReport;
}

export function PostmortemModal({
  isOpen,
  onClose,
  report = SAMPLE_POSTMORTEM,
}: PostmortemModalProps) {
  const [copied, setCopied] = useState(false);

  if (!isOpen) return null;

  const generateMarkdown = () => {
    return `# SRE INCIDENT POSTMORTEM REPORT: ${report.incidentId}
**Title:** ${report.title}
**Service:** ${report.websiteName}
**Severity:** ${report.severity}
**Duration of Impact:** ${report.impactDuration}
**Lead Investigator:** ${report.leadInvestigator}
**Detection Time:** ${report.detectionTime}
**Resolution Time:** ${report.resolutionTime}

---

## 1. Executive Summary
${report.summary}

## 2. Root Cause Analysis
${report.rootCause}

## 3. Timeline of Events
${report.timeline.map((t) => `- **${t.time}**: ${t.event}`).join('\n')}

## 4. Remediation Steps Taken
${report.remediationSteps.map((s) => `1. ${s}`).join('\n')}

## 5. Preventative Action Items
${report.actionItems.map((a) => `- [ ] ${a}`).join('\n')}

---
*Generated by TARSIER — Your Night Guard | Team Rocket Autonomous Incident Platform*
`;
  };

  const handleDownloadMarkdown = () => {
    const md = generateMarkdown();
    const blob = new Blob([md], { type: 'text/markdown;charset=utf-8' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = `postmortem-${report.incidentId}.md`;
    document.body.appendChild(a);
    a.click();
    document.body.removeChild(a);
    URL.revokeObjectURL(url);
  };

  const handleDownloadJson = () => {
    const jsonStr = JSON.stringify(report, null, 2);
    const blob = new Blob([jsonStr], { type: 'application/json;charset=utf-8' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = `postmortem-${report.incidentId}.json`;
    document.body.appendChild(a);
    a.click();
    document.body.removeChild(a);
    URL.revokeObjectURL(url);
  };

  const handleCopyMarkdown = () => {
    navigator.clipboard.writeText(generateMarkdown());
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center p-4 bg-black/85 backdrop-blur-md animate-in fade-in duration-200">
      <div className="relative w-full max-w-2xl rounded-2xl bg-[#0D0D10] border border-white/10 p-6 sm:p-8 shadow-2xl flex flex-col max-h-[90vh]">
        {/* Close Button */}
        <button
          onClick={onClose}
          className="absolute top-5 right-5 text-neutral-400 hover:text-white p-1 rounded-lg hover:bg-white/5 transition-colors cursor-pointer"
        >
          <X className="w-5 h-5" />
        </button>

        {/* Modal Header */}
        <div className="flex items-center space-x-3 mb-6">
          <div className="w-10 h-10 rounded-xl bg-[#007AFF]/20 border border-[#007AFF]/40 flex items-center justify-center text-[#007AFF]">
            <FileText className="w-5 h-5" />
          </div>
          <div>
            <div className="flex items-center gap-2">
              <h2 className="text-lg font-bold text-white tracking-tight">Incident Postmortem Report</h2>
              <span className="text-[10px] font-mono px-2 py-0.5 rounded bg-white/10 text-neutral-300">
                {report.incidentId}
              </span>
            </div>
            <p className="text-xs text-neutral-400">
              Audit-ready SRE postmortem with timeline, root cause, and action items.
            </p>
          </div>
        </div>

        {/* Scrollable Report Body */}
        <div className="flex-1 overflow-y-auto space-y-6 pr-2 text-left font-sans">
          {/* Metadata Grid */}
          <div className="grid grid-cols-2 sm:grid-cols-4 gap-3 p-4 rounded-xl bg-[#15151A] border border-white/5 text-xs">
            <div>
              <div className="text-neutral-400 text-[11px]">Severity</div>
              <div className="text-red-400 font-semibold mt-0.5">{report.severity}</div>
            </div>
            <div>
              <div className="text-neutral-400 text-[11px]">Impact Duration</div>
              <div className="text-white font-semibold mt-0.5">{report.impactDuration}</div>
            </div>
            <div>
              <div className="text-neutral-400 text-[11px]">Detected By</div>
              <div className="text-white font-semibold mt-0.5">Synthetic Sentinel</div>
            </div>
            <div>
              <div className="text-neutral-400 text-[11px]">Lead SRE</div>
              <div className="text-white font-semibold mt-0.5">Vikrant S.</div>
            </div>
          </div>

          {/* Section 1: Executive Summary */}
          <div>
            <h3 className="text-xs font-bold uppercase tracking-wider text-[#007AFF] mb-1.5">
              1. Executive Summary
            </h3>
            <p className="text-xs sm:text-sm text-neutral-300 leading-relaxed bg-[#15151A] p-4 rounded-xl border border-white/5">
              {report.summary}
            </p>
          </div>

          {/* Section 2: Root Cause Analysis */}
          <div>
            <h3 className="text-xs font-bold uppercase tracking-wider text-[#007AFF] mb-1.5">
              2. Root Cause Analysis
            </h3>
            <p className="text-xs sm:text-sm text-neutral-300 leading-relaxed bg-[#15151A] p-4 rounded-xl border border-white/5">
              {report.rootCause}
            </p>
          </div>

          {/* Section 3: Timeline */}
          <div>
            <h3 className="text-xs font-bold uppercase tracking-wider text-[#007AFF] mb-2">
              3. Incident Timeline
            </h3>
            <div className="space-y-2 border-l border-white/10 pl-4 ml-2">
              {report.timeline.map((item, idx) => (
                <div key={idx} className="relative text-xs">
                  <div className="absolute -left-[21px] top-1.5 w-2 h-2 rounded-full bg-[#007AFF]" />
                  <span className="font-mono text-neutral-400">{item.time}</span> —{' '}
                  <span className="text-neutral-200">{item.event}</span>
                </div>
              ))}
            </div>
          </div>

          {/* Section 4: Remediation Steps */}
          <div>
            <h3 className="text-xs font-bold uppercase tracking-wider text-emerald-400 mb-2">
              4. Remediation Steps Executed
            </h3>
            <div className="p-3.5 rounded-xl bg-[#15151A] border border-white/5 space-y-1.5 text-xs text-neutral-300">
              {report.remediationSteps.map((step, idx) => (
                <div key={idx} className="flex items-start space-x-2">
                  <CheckCircle2 className="w-4 h-4 text-emerald-400 shrink-0 mt-0.5" />
                  <span>{step}</span>
                </div>
              ))}
            </div>
          </div>

          {/* Section 5: Action Items */}
          <div>
            <h3 className="text-xs font-bold uppercase tracking-wider text-amber-400 mb-2">
              5. Preventative Action Items
            </h3>
            <div className="p-3.5 rounded-xl bg-[#15151A] border border-white/5 space-y-1.5 text-xs text-neutral-300">
              {report.actionItems.map((item, idx) => (
                <div key={idx} className="flex items-start space-x-2">
                  <span className="text-neutral-400 font-mono">[{idx + 1}]</span>
                  <span>{item}</span>
                </div>
              ))}
            </div>
          </div>
        </div>

        {/* Footer Actions */}
        <div className="pt-4 mt-4 border-t border-white/10 flex flex-wrap items-center justify-between gap-3">
          <button
            onClick={handleCopyMarkdown}
            className="flex items-center space-x-1.5 px-3.5 py-2 rounded-xl bg-[#15151A] hover:bg-white/10 text-neutral-300 hover:text-white text-xs font-semibold border border-white/10 transition-colors cursor-pointer"
          >
            {copied ? <Check className="w-3.5 h-3.5 text-emerald-400" /> : <Copy className="w-3.5 h-3.5" />}
            <span>{copied ? 'Copied Markdown' : 'Copy Markdown'}</span>
          </button>

          <div className="flex items-center space-x-2">
            <button
              onClick={handleDownloadJson}
              className="flex items-center space-x-1.5 px-3.5 py-2 rounded-xl bg-[#15151A] hover:bg-white/10 text-neutral-300 hover:text-white text-xs font-semibold border border-white/10 transition-colors cursor-pointer"
            >
              <Download className="w-3.5 h-3.5" />
              <span>Download (.json)</span>
            </button>
            <button
              onClick={handleDownloadMarkdown}
              className="flex items-center space-x-1.5 px-4 py-2 rounded-xl bg-[#007AFF] hover:bg-[#0066D6] text-white text-xs font-semibold shadow-[0_0_15px_rgba(0,122,255,0.3)] transition-all cursor-pointer"
            >
              <Download className="w-3.5 h-3.5" />
              <span>Download (.md)</span>
            </button>
          </div>
        </div>
      </div>
    </div>
  );
}
